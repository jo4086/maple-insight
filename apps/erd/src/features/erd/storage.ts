import type { ErdDocument, ErdEntity, ErdRelationCardinality } from './types';

const STORAGE_KEY = 'erd-documents';
const DEFAULT_ENTITY_WIDTH = 420;
const DEFAULT_ENTITY_HEIGHT = 240;
const DEFAULT_ENTITY_COLOR = '#0f172a';

function normalizeEntity(entity: ErdEntity): ErdEntity {
  return {
    ...entity,
    color: entity.color ?? DEFAULT_ENTITY_COLOR,
    isUniqueColumnVisible: entity.isUniqueColumnVisible ?? false,
    size: entity.size ?? {
      width: DEFAULT_ENTITY_WIDTH,
      height: DEFAULT_ENTITY_HEIGHT,
    },
    columns: (entity.columns ?? []).map((column) => ({
      ...column,
      relationKeyType: column.relationKeyType ?? null,
      referencedEntityId: column.referencedEntityId ?? null,
      referencedColumnId: column.referencedColumnId ?? null,
      referencedRelationId: column.referencedRelationId ?? null,
    })),
  };
}

function normalizeRelations(relations: ErdDocument['relations']) {
  const normalizeCardinality = (value: unknown, fallback: ErdRelationCardinality): ErdRelationCardinality => {
    const allowed: ErdRelationCardinality[] = ['one', 'one-only', 'zero-or-one', 'many', 'zero-or-many', 'one-or-many'];
    return typeof value === 'string' && allowed.includes(value as ErdRelationCardinality) ? (value as ErdRelationCardinality) : fallback;
  };

  return (relations ?? []).map((relation) => {
    const legacyRelation = relation as typeof relation & { kind?: unknown };

    return {
      ...relation,
      fromColumnId: relation.fromColumnId ?? null,
      toColumnId: relation.toColumnId ?? null,
      fromCardinality: normalizeCardinality('fromCardinality' in relation ? relation.fromCardinality : null, 'one'),
      toCardinality: normalizeCardinality('toCardinality' in relation ? relation.toCardinality : legacyRelation.kind, 'zero-or-many'),
      relationshipType: 'relationshipType' in relation && relation.relationshipType ? relation.relationshipType : 'non-identifying',
    };
  });
}

