function createSeedDocuments(): ErdDocument[] {
  return [
    {
      id: 'erd-sample',
      thumbnail: null,
      title: 'Sample ERD',
      updatedAt: new Date().toISOString(),
      entities: [createUsersEntity()],
      memos: [
        {
          id: 'memo-1',
          title: '메모',
          content: 'ENUM 기본 전략은 TEXT + CHECK',
        },
      ],
      relations: [],
    },
  ];
}

export function loadErdDocuments(): ErdDocument[] {
  const raw = window.localStorage.getItem(STORAGE_KEY);
  if (!raw) {
    const seed = createSeedDocuments();
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify(seed));
    return seed;
  }

  try {
    const parsed = JSON.parse(raw) as ErdDocument[];
    return Array.isArray(parsed)
      ? parsed.map((document) => ({
          ...document,
          thumbnail: document.thumbnail ?? null,
          entities: Array.isArray(document.entities) ? document.entities.map(normalizeEntity) : [],
          relations: normalizeRelations(document.relations),
        }))
      : createSeedDocuments();
  } catch {
    return createSeedDocuments();
  }
}

export function saveErdDocuments(documents: ErdDocument[]) {
  window.localStorage.setItem(STORAGE_KEY, JSON.stringify(documents));
}

export function createEmptyDocument(): ErdDocument {
  return {
    id: crypto.randomUUID(),
    thumbnail: null,
    title: 'Untitled ERD',
    updatedAt: new Date().toISOString(),
    entities: [],
    memos: [],
    relations: [],
  };
}

export function removeErdDocument(documentId: string) {
  const documents = loadErdDocuments().filter((document) => document.id !== documentId);
  saveErdDocuments(documents);
  return documents;
}

export function updateErdDocumentThumbnail(documentId: string, thumbnail: string | null) {
  const documents = loadErdDocuments().map((document) =>
    document.id === documentId
      ? {
          ...document,
          thumbnail,
          updatedAt: new Date().toISOString(),
        }
      : document,
  );
  saveErdDocuments(documents);
  return documents;
}

export function duplicateErdDocument(documentId: string) {
  const documents = loadErdDocuments();
  const source = documents.find((document) => document.id === documentId);

  if (!source) return null;

  const entityIdMap = new Map<string, string>();
  const columnIdMap = new Map<string, string>();

  const duplicatedEntities = source.entities.map((entity) => {
    const nextEntityId = crypto.randomUUID();
    entityIdMap.set(entity.id, nextEntityId);

    return {
      ...entity,
      id: nextEntityId,
      columns: entity.columns.map((column) => {
        const nextColumnId = crypto.randomUUID();
        columnIdMap.set(column.id, nextColumnId);
        return {
          ...column,
          id: nextColumnId,
        };
      }),
    };
  });

  const duplicatedDocument: ErdDocument = {
    ...source,
    id: crypto.randomUUID(),
    thumbnail: source.thumbnail,
    title: `${source.title} Copy`,
    updatedAt: new Date().toISOString(),
    entities: duplicatedEntities,
    memos: source.memos.map((memo) => ({
      ...memo,
      id: crypto.randomUUID(),
    })),
    relations: source.relations.map((relation) => ({
      ...relation,
      id: crypto.randomUUID(),
      fromEntityId: relation.fromEntityId ? (entityIdMap.get(relation.fromEntityId) ?? relation.fromEntityId) : relation.fromEntityId,
      fromColumnId: relation.fromColumnId ? (columnIdMap.get(relation.fromColumnId) ?? relation.fromColumnId) : relation.fromColumnId,
      toEntityId: relation.toEntityId ? (entityIdMap.get(relation.toEntityId) ?? relation.toEntityId) : relation.toEntityId,
      toColumnId: relation.toColumnId ? (columnIdMap.get(relation.toColumnId) ?? relation.toColumnId) : relation.toColumnId,
    })),
  };

  saveErdDocuments([duplicatedDocument, ...documents]);
  return duplicatedDocument;
}
